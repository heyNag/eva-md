type parser struct {
	source    Source
	turn      string
	blocked   bool
	offRecord bool
	control   string // the record control the last row gave, if any
}

func newParser(s Source) *parser { return &parser{source: s} }
func stringValue(m map[string]json.RawMessage, key string) string {
	var s string
	_ = json.Unmarshal(m[key], &s)
	return s
}
func boolValue(m map[string]json.RawMessage, key string) bool {
	var b bool
	_ = json.Unmarshal(m[key], &b)
	return b
}
func (p *parser) read(line []byte) (inbox.Entry, bool) {
	p.control = ""
	var row map[string]json.RawMessage
	if json.Unmarshal(line, &row) != nil {
		return inbox.Entry{}, false
	}
	e := p.source.Entry
	e.Origin = "catchup"
	e.Text = ""
	e.Role = ""
	e.Kind = ""
	e.Turn = ""
	e.TS = stringValue(row, "timestamp")
	if _, err := time.Parse(time.RFC3339Nano, e.TS); err != nil {
		return e, false
	}
	// control is the text a user row is checked against for a privacy
	// control; typed says whether the row reads as a prompt the user typed.
	control, typed := "", false
	if p.source.Host == "claude-code" {
		if stringValue(row, "sessionId") != p.source.Session || !sameCwd(stringValue(row, "cwd"), p.source.Cwd) || boolValue(row, "isMeta") || boolValue(row, "isSidechain") {
			return e, false
		}
		if stringValue(row, "agentId") != "" || stringValue(row, "agent_id") != "" {
			return e, false
		}
		if origin := stringValue(row, "turnOrigin"); origin != "" && origin != "human" {
			return e, false
		}
		var origin map[string]json.RawMessage
		if json.Unmarshal(row["origin"], &origin) == nil {
			if kind := stringValue(origin, "kind"); kind != "" && kind != "human" {
				return e, false
			}
		}
		var message map[string]json.RawMessage
		if json.Unmarshal(row["message"], &message) != nil {
			return e, false
		}
		e.Turn = stringValue(row, "promptId")
		if e.Turn == "" {
			e.Turn = stringValue(row, "prompt_id")
		}
		switch stringValue(row, "type") {
		case "user":
			if stringValue(message, "role") != "user" {
				return e, false
			}
			// Claude serializes compaction summaries and their display copies as
			// user messages. They are host output, not the user's words; the
			// PostCompact hook captures the summary with the correct provenance.
			// Visibility alone does not establish authorship, so don't filter on
			// isVisibleInTranscriptOnly without one of these explicit flags.
			if boolValue(row, "isCompactSummary") || boolValue(row, "repeatsCompactSummary") {
				return e, false
			}
			e.Text, control = userText(message["content"])
			e.Role = "user"
			e.Kind = "prompt"
			if e.Turn != "" {
				p.turn = e.Turn
			}
			// Claude also writes user rows the user did not type: bash-mode
			// input and its output, interrupt notices and command banners.
			// Accept a row as a prompt only by allowlist: it carries its own
			// prompt id and does not start with a host wrapper.
			typed = e.Turn != "" && !hostWrapper(e.Text)
		case "assistant":
			if stringValue(message, "role") != "assistant" {
				return e, false
			}
			// Resume-loader placeholders and API-error displays use assistant
			// rows too, but are not final answers generated by the model. Check
			// host metadata rather than matching potentially legitimate text.
			if stringValue(message, "model") == "<synthetic>" || boolValue(row, "isApiErrorMessage") {
				return e, false
			}
			stop := stringValue(message, "stop_reason")
			if stop != "end_turn" && stop != "stop_sequence" {
				return e, false
			}
			e.Text = textContent(message["content"], true)
			e.Role = "assistant"
			e.Kind = "reply"
			if e.Turn == "" {
				e.Turn = p.turn
			}
		default:
			return e, false
		}
	} else {
		var value map[string]json.RawMessage
		if json.Unmarshal(row["payload"], &value) != nil {
			return e, false
		}
		switch stringValue(row, "type") {
		case "turn_context":
			if cwd := stringValue(value, "cwd"); cwd != "" && !sameCwd(cwd, p.source.Cwd) {
				p.blocked = true
			}
			p.turn = stringValue(value, "turn_id")
			return e, false
		case "event_msg":
			switch stringValue(value, "type") {
			case "task_started":
				p.turn = stringValue(value, "turn_id")
				return e, false
			case "user_message":
				e.Role = "user"
				e.Kind = "prompt"
				e.Text = stringValue(value, "message")
				control, typed = e.Text, true
			case "agent_message":
				if stringValue(value, "phase") != "final" {
					return e, false
				}
				e.Role = "assistant"
				e.Kind = "reply"
				e.Text = stringValue(value, "message")
			case "task_complete":
				e.Role = "assistant"
				e.Kind = "reply"
				e.Text = stringValue(value, "last_agent_message")
			default:
				return e, false
			}
			e.Turn = stringValue(value, "turn_id")
			if e.Turn == "" {
				e.Turn = p.turn
			}
		case "response_item":
			if stringValue(value, "type") != "message" || stringValue(value, "role") != "assistant" || stringValue(value, "phase") != "final" {
				return e, false
			}
			e.Role = "assistant"
			e.Kind = "reply"
			e.Text = textContent(value["content"], true)
			e.Turn = p.turn
		default:
			return e, false
		}
	}
	// Recovery never interprets privacy phrases as ordinary stored prompts. This
	// protects a missed control hook as well as the durable off-record boundary.
	// The check runs on the raw text, before any redaction, and also reads the
	// text beside an attachment, so a pasted screenshot can't hide a control.
	if e.Role == "user" {
		if p.blocked || strings.TrimSpace(control) == "" || syntheticText(control) {
			return e, false
		}
		switch recordControl(control) {
		case "off_record":
			p.blocked = true
			p.offRecord = true
			p.control = "off_record"
			return e, false
		case "on_record":
			p.control = "on_record"
			return e, false
		}
		if !typed {
			return e, false
		}
	}
	if p.blocked || strings.TrimSpace(e.Text) == "" || syntheticText(e.Text) {
		return e, false
	}
	return e, true
}
func textContent(raw json.RawMessage, assistant bool) string {
	var text string
	if json.Unmarshal(raw, &text) == nil {
		return text
	}
	var items []map[string]json.RawMessage
	if json.Unmarshal(raw, &items) != nil {
		return ""
	}
	var parts []string
	for _, item := range items {
		kind := stringValue(item, "type")
		if kind == "text" || assistant && kind == "output_text" {
			parts = append(parts, stringValue(item, "text"))
		} else {
			return ""
		}
	}
	return strings.Join(parts, "\n")
}

// userText reads a Claude user message's content. stored is the text that may
// be stored: the content when it is all text. control is the text checked for
// a privacy control: the text items joined, also beside an image or document
// attachment, but none at all when an item is a tool result, which is tool
// output rather than the user's words. rowScan applies the same rules to rows
// too large to decode here.
func userText(raw json.RawMessage) (stored, control string) {
	var text string
	if json.Unmarshal(raw, &text) == nil {
		return text, text
	}
	var items []map[string]json.RawMessage
	if json.Unmarshal(raw, &items) != nil {
		return "", ""
	}
	var parts []string
	attached := false
	for _, item := range items {
		switch stringValue(item, "type") {
		case "text":
			parts = append(parts, stringValue(item, "text"))
		case "tool_result":
			return "", ""
		default:
			attached = true
		}
	}
	joined := strings.Join(parts, "\n")
	if attached {
		return "", joined
	}
	return joined, joined
}
func syntheticText(text string) bool {
	lower := lowerHead(text)
	for _, prefix := range []string{"<task-notification>", "<teammate-message", "<system-reminder>", "<local-command-stdout>", "<command-name>", "[message from ", "## memory writing agent", "# agents.md instructions", "<environment_context>", "<permissions instructions>", "/loop ", "/clear", "/compact"} {
		if strings.HasPrefix(lower, prefix) {
			return true
		}
	}
	return false
}

// headRunes is how much of a text lowerHead keeps: more than the longest
// prefix syntheticText and hostWrapper look for.
const headRunes = 64

// lowerHead returns the start of strings.ToLower(strings.TrimSpace(text)),
// at least headRunes runes of it, without lower-casing the rest of a long
// paste. ToLower maps rune by rune, so the start of the whole result is the
// result of the start.
func lowerHead(text string) string {
	text = strings.TrimLeftFunc(text, unicode.IsSpace)
	text = strings.TrimRightFunc(text, unicode.IsSpace) // costs only the trailing space
	n := 0
	for i := range text {
		if n == headRunes {
			text = text[:i]
			break
		}
		n++
	}
	return strings.ToLower(text)
}

// hostWrapper reports whether a Claude user row's text starts with one of the
// wrappers Claude Code puts around text the user did not type as a prompt:
// bash-mode input and output, slash-command banners and output, and interrupt
// notices. Such rows are never stored as the user's words, and command output
// is never stored at all.
func hostWrapper(text string) bool {
	lower := lowerHead(text)
	for _, prefix := range []string{"<bash-input>", "<bash-stdout>", "<bash-stderr>", "<command-message>", "<command-name>", "<command-args>", "<local-command-stdout>", "<local-command-stderr>", "[request interrupted by user"} {
		if strings.HasPrefix(lower, prefix) {
			return true
		}
	}
	return false
}

// recordControl is session.RecordControl with an exact, cheap prefilter. Both
// phrases end in the word "record", and only the ASCII letters r, e, c, o and
// d lower-case to those letters, so text without "record" in some ASCII case
// cannot hold either phrase. A long paste then skips the full normalization.
// A long text that does hold the word is checked in one streaming pass
// (ctlText) instead of RecordControl's four, which gives the same answer:
// about 22 ms rather than 95 for a 975 KB paste of Greek prose.
func recordControl(text string) string {
	if !containsRecord(text) {
		return ""
	}
	if len(text) > streamControl {
		var c ctlText
		for _, r := range text {
			c.rune(r)
		}
		return c.verdict()
	}
	return session.RecordControl(text)
}

// streamControl is the text length above which recordControl streams.
const streamControl = 16 << 10

func containsRecord(text string) bool {
	const word = "record"
	for i := 0; i+len(word) <= len(text); {
		j := strings.IndexAny(text[i:len(text)-len(word)+1], "rR")
		if j < 0 {
			return false
		}
		i += j
		if strings.EqualFold(text[i:i+len(word)], word) {
			return true
		}
		i++
	}
	return false
}

// Codex messages don't repeat session identity, so verify the opening metadata
// before considering the tail. Unknown layouts are deliberately not recovered.
func codexIdentity(data []byte, s Source) bool {
	for _, line := range bytes.Split(data, []byte{'\n'}) {
		var row map[string]json.RawMessage
		if json.Unmarshal(line, &row) != nil {
			continue
		}
		if stringValue(row, "type") != "session_meta" {
			continue
		}
		var payload map[string]json.RawMessage
		if json.Unmarshal(row["payload"], &payload) != nil {
			return false
		}
		return stringValue(payload, "id") == s.Session && sameCwd(stringValue(payload, "cwd"), s.Cwd)
	}
	return false
}

func sameCwd(a, b string) bool {
	if !filepath.IsAbs(a) || !filepath.IsAbs(b) {
		return false
	}
	if filepath.Clean(a) == filepath.Clean(b) {
		return true
	}
	aa, e := filepath.EvalSymlinks(a)
	if e != nil {
		return false
	}
	bb, e := filepath.EvalSymlinks(b)
	return e == nil && aa == bb
}

// Rows too long for recovery's window
//
// A row longer than the window, such as a pasted screenshot or an image or
// PDF a tool read, can't be decoded in one piece within a hook's budget. A
// size is never a reason to go off the record, so recovery streams past such
// a row in bounded chunks with rowScan. The scan keeps only what the privacy
// check needs: a few short fields, and whether the user's own text holds a
// record control. Long strings, such as an image's base64 data or a tool
// result, are skipped without being decoded. The exported fields are the
// scan's whole state, saved with the cursor, so a scan that runs out of time
// resumes in the next pass instead of starting over.

// What the scanner expects next.
const (
	scanValue   = iota // a value
	scanAfter          // a comma or closing bracket after a value
	scanKey            // an object key or '}'
	scanColon          // ':' after a key
	scanString         // the inside of a string
	scanLiteral        // the inside of true, false, null or a number
	scanEnd            // nothing more: the row's object has closed
)

// What the string being read feeds.
const (
	feedSkip  = iota // nothing: skip to its end
	feedKey          // the key of the innermost object
	feedField        // a short field, kept raw
	feedText         // a text checked for a record control, decoded
)

// Short fields kept from a row.
const (
	fieldType = iota
	fieldSession
	fieldCwd
	fieldTimestamp
	fieldAgent
	fieldAgentAlt
	fieldTurnOrigin
	fieldOriginKind
	fieldRole
	fieldItemType
	fieldPayloadType
	fieldCount
)

// Flags kept from a row.
const (
	flagMeta = iota
	flagSidechain
	flagCompact
	flagRepeats
	flagCount
)

// Texts checked for a record control.
const (
	textRow     = iota // the message content: a string, or its text items merged
	textItem           // the text of the current content item
	textPayload        // a Codex user message
)

// What a value is, judged by where it sits in the row.
const (
	roleSkip = iota
	roleRoot
	roleField
	roleFlag
	roleMessage
	roleOrigin
	rolePayload
	roleContent
	roleItem
	roleText
)

// Escape states inside a decoded string.
const (
	escNone      = iota
	escBackslash // after '\'
	escHex       // inside the four digits of \uXXXX
)

const (
	scanMaxDepth = 32 // deeper rows are not understood; only their end matters
	scanMaxKey   = 64 // longer keys match nothing kept
	scanMaxLit   = 8
)

// fieldLimit caps a kept field: a longer one can't be a valid value, and the
// caps keep the scan's state small enough to save with the cursor.
func fieldLimit(which int) int {
	if which == fieldCwd {
		return 4096
	}
	return 256
}

var (
	topFields = map[string]int{"type": fieldType, "sessionId": fieldSession, "cwd": fieldCwd, "timestamp": fieldTimestamp, "agentId": fieldAgent, "agent_id": fieldAgentAlt, "turnOrigin": fieldTurnOrigin}
	topFlags  = map[string]int{"isMeta": flagMeta, "isSidechain": flagSidechain, "isCompactSummary": flagCompact, "repeatsCompactSummary": flagRepeats}
)

type rowScan struct {
	Start   int64  `json:"start"`             // the row's first byte
	Pos     int64  `json:"pos"`               // the next byte to scan; past the row once Done
	Done    bool   `json:"done,omitempty"`    // the row's end was reached
	Partial bool   `json:"partial,omitempty"` // the row began before the registered cursor
	Bad     bool   `json:"bad,omitempty"`     // not JSON this scanner follows
	Gap     string `json:"gap,omitempty"`     // the gap event the row leaves; gapTooLarge when empty

	State   int         `json:"state"`
	Stack   []scanFrame `json:"stack,omitempty"`
	Feed    int         `json:"feed,omitempty"`     // what the current string feeds
	Which   int         `json:"which,omitempty"`    // which field, flag or text
	LitRole int         `json:"lit_role,omitempty"` // what the current literal is
	Esc     int         `json:"esc,omitempty"`
	Hex     int         `json:"hex,omitempty"`
	Digit   int         `json:"digit,omitempty"`
	High    int         `json:"high,omitempty"` // a high surrogate waiting for its pair
	UTF8    []byte      `json:"utf8,omitempty"` // an incomplete UTF-8 sequence
	Buf     []byte      `json:"buf,omitempty"`  // the key or field being read, raw
	Long    bool        `json:"long,omitempty"` // Buf passed its limit
	Lit     []byte      `json:"lit,omitempty"`

	Fields     [fieldCount][]byte `json:"fields"`
	Flags      [flagCount]bool    `json:"flags"`
	MessageObj bool               `json:"message_obj,omitempty"`
	OriginObj  bool               `json:"origin_obj,omitempty"`
	PayloadObj bool               `json:"payload_obj,omitempty"`
	Content    int                `json:"content,omitempty"` // 0 none, 1 string, 2 array, 3 other
	ToolResult bool               `json:"tool_result,omitempty"`
	BadItem    bool               `json:"bad_item,omitempty"`
	Texts      [3]ctlText         `json:"texts"`
}

type scanFrame struct {
	Obj  bool   `json:"o,omitempty"`
	Key  []byte `json:"k,omitempty"`
	Long bool   `json:"l,omitempty"`
}

// feed scans part of the row; data holds no newline.
func (z *rowScan) feed(data []byte) {
	quote, slash := -1, -1 // the next '"' and '\' at or after i, once looked up
	for i := 0; i < len(data) && !z.Bad; {
		c := data[i]
		switch z.State {
		case scanString:
			if z.Feed == feedSkip && z.Esc == escNone {
				// Jump over a skipped string's content. Each lookup resumes
				// after the previous match, so this stays linear in the row.
				if quote < i {
					quote = indexFrom(data, i, '"')
				}
				if slash < i {
					slash = indexFrom(data, i, '\\')
				}
				i = min(quote, slash)
				if i >= len(data) {
					return
				}
				c = data[i]
			}
			i++
			z.stringByte(c)
		case scanLiteral:
			if c == '-' || c == '+' || c == '.' || c >= '0' && c <= '9' || c >= 'a' && c <= 'z' || c >= 'A' && c <= 'Z' {
				if len(z.Lit) < scanMaxLit {
					z.Lit = append(z.Lit, c)
				}
				i++
				continue
			}
			z.endLiteral() // and look at c again in the new state
		default:
			i++
			z.structural(c)
		}
	}
}

func indexFrom(data []byte, i int, c byte) int {
	if j := bytes.IndexByte(data[i:], c); j >= 0 {
		return i + j
	}
	return len(data)
}

func (z *rowScan) structural(c byte) {
	if c == ' ' || c == '\t' || c == '\r' || c == '\n' {
		return
	}
	switch z.State {
	case scanValue:
		z.beginValue(c)
	case scanKey:
		switch {
		case c == '"':
			z.beginString(feedKey, 0)
		case c == '}' && z.top(true):
			z.pop()
		default:
			z.Bad = true
		}
	case scanColon:
		if c != ':' {
			z.Bad = true
			return
		}
		z.State = scanValue
	case scanAfter:
		switch {
		case c == ',' && z.top(true):
			z.State = scanKey
		case c == ',' && z.top(false):
			z.State = scanValue
		case c == '}' && z.top(true), c == ']' && z.top(false):
			z.pop()
		default:
			z.Bad = true
		}
	default:
		z.Bad = true
	}
}

// top reports whether the innermost container is an object (obj) or an array.
func (z *rowScan) top(obj bool) bool {
	return len(z.Stack) > 0 && z.Stack[len(z.Stack)-1].Obj == obj
}

func (z *rowScan) beginValue(c byte) {
	if c == ']' && z.top(false) {
		z.pop() // an empty array
		return
	}
	role, which := z.role()
	switch {
	case c == '{':
		z.onValue(role, which, 'o')
		if len(z.Stack) >= scanMaxDepth {
			z.Bad = true
			return
		}
		z.Stack = append(z.Stack, scanFrame{Obj: true})
		z.State = scanKey
	case c == '[':
		z.onValue(role, which, 'a')
		if len(z.Stack) >= scanMaxDepth {
			z.Bad = true
			return
		}
		z.Stack = append(z.Stack, scanFrame{})
		z.State = scanValue
	case c == '"':
		z.onValue(role, which, 's')
		feed := feedSkip
		switch role {
		case roleField:
			feed = feedField
		case roleText:
			feed = feedText
		case roleContent:
			feed, which = feedText, textRow
		}
		z.beginString(feed, which)
	case c == '-' || c >= '0' && c <= '9' || c == 't' || c == 'f' || c == 'n':
		z.onValue(role, which, 'l')
		z.LitRole, z.Which = role, which
		z.Lit = append(z.Lit[:0], c)
		z.State = scanLiteral
	default:
		z.Bad = true
	}
}

// role says what the value about to start is, from the keys that lead to it.
func (z *rowScan) role() (int, int) {
	n := len(z.Stack)
	if n == 0 {
		return roleRoot, 0
	}
	key := func(i int) string {
		if z.Stack[i].Long || !z.Stack[i].Obj {
			return "\x00"
		}
		return string(z.Stack[i].Key)
	}
	switch {
	case n == 1 && z.Stack[0].Obj:
		k := key(0)
		if f, ok := topFields[k]; ok {
			return roleField, f
		}
		if f, ok := topFlags[k]; ok {
			return roleFlag, f
		}
		switch k {
		case "message":
			return roleMessage, 0
		case "origin":
			return roleOrigin, 0
		case "payload":
			return rolePayload, 0
		}
	case n == 2 && z.Stack[1].Obj:
		switch key(0) + "." + key(1) {
		case "message.role":
			return roleField, fieldRole
		case "message.content":
			return roleContent, 0
		case "origin.kind":
			return roleField, fieldOriginKind
		case "payload.type":
			return roleField, fieldPayloadType
		case "payload.message":
			return roleText, textPayload
		}
	case n == 3 && !z.Stack[2].Obj && key(0) == "message" && key(1) == "content":
		return roleItem, 0
	case n == 4 && z.Stack[3].Obj && z.inItem():
		switch key(3) {
		case "type":
			return roleField, fieldItemType
		case "text":
			return roleText, textItem
		}
	}
	return roleSkip, 0
}

// inItem reports whether the innermost object is an item of message.content.
func (z *rowScan) inItem() bool {
	s := z.Stack
	return len(s) == 4 && s[0].Obj && !s[0].Long && string(s[0].Key) == "message" && s[1].Obj && !s[1].Long && string(s[1].Key) == "content" && !s[2].Obj && s[3].Obj
}

// onValue resets what a value replaces when it starts. As when the row is
// decoded into a map, the last of repeated keys wins.
func (z *rowScan) onValue(role, which int, kind byte) {
	switch role {
	case roleRoot:
		if kind != 'o' {
			z.Bad = true
		}
	case roleField:
		if which >= 0 && which < fieldCount {
			z.Fields[which] = nil
		}
	case roleFlag:
		if which >= 0 && which < flagCount {
			z.Flags[which] = false
		}
	case roleMessage:
		z.MessageObj = kind == 'o'
		z.Fields[fieldRole] = nil
		z.Content, z.ToolResult, z.BadItem = 0, false, false
		z.Texts[textRow], z.Texts[textItem] = ctlText{}, ctlText{}
	case roleOrigin:
		z.OriginObj = kind == 'o'
		z.Fields[fieldOriginKind] = nil
	case rolePayload:
		z.PayloadObj = kind == 'o'
		z.Fields[fieldPayloadType] = nil
		z.Texts[textPayload] = ctlText{}
	case roleContent:
		z.ToolResult, z.BadItem = false, false
		z.Texts[textRow], z.Texts[textItem] = ctlText{}, ctlText{}
		switch kind {
		case 's':
			z.Content = 1
		case 'a':
			z.Content = 2
		default:
			z.Content = 3
		}
	case roleItem:
		z.Fields[fieldItemType] = nil
		z.Texts[textItem] = ctlText{}
		if kind == 's' || kind == 'a' {
			z.BadItem = true // decoding the items into objects would fail
		}
	case roleText:
		if which >= 0 && which < len(z.Texts) {
			z.Texts[which] = ctlText{}
		}
	}
}

func (z *rowScan) beginString(feed, which int) {
	z.State = scanString
	z.Feed, z.Which = feed, which
	z.Esc, z.Hex, z.Digit, z.High = escNone, 0, 0, 0
	z.UTF8, z.Buf, z.Long = z.UTF8[:0], z.Buf[:0], false
}

func (z *rowScan) stringByte(c byte) {
	switch z.Feed {
	case feedText:
		z.textByte(c)
		return
	case feedKey, feedField:
		limit := scanMaxKey
		if z.Feed == feedField {
			limit = fieldLimit(z.Which)
		}
		switch {
		case z.Esc == escNone && c == '"':
			z.endString()
			return
		case z.Esc == escNone && c < 0x20:
			z.Bad = true
			return
		case z.Esc == escNone && c == '\\':
			z.Esc = escBackslash
		default:
			z.Esc = escNone
		}
		if len(z.Buf) < limit {
			z.Buf = append(z.Buf, c)
		} else {
			z.Long = true
		}
	default:
		switch {
		case z.Esc != escNone:
			z.Esc = escNone
		case c == '\\':
			z.Esc = escBackslash
		case c == '"':
			z.endString()
		}
	}
}

// textByte decodes a text string exactly as encoding/json does, escapes,
// surrogate pairs and invalid UTF-8 included, and feeds its runes on.
func (z *rowScan) textByte(c byte) {
	switch z.Esc {
	case escHex:
		v := hexValue(c)
		if v < 0 {
			z.Bad = true
			return
		}
		z.Hex = z.Hex<<4 | v
		if z.Digit++; z.Digit < 4 {
			return
		}
		z.Esc = escNone
		z.unit(rune(z.Hex))
		return
	case escBackslash:
		z.Esc = escNone
		if z.High != 0 && c != 'u' {
			z.emit(unicode.ReplacementChar) // the high surrogate has no pair
			z.High = 0
		}
		switch c {
		case '"', '\\', '/':
			z.emit(rune(c))
		case 'b':
			z.emit('\b')
		case 'f':
			z.emit('\f')
		case 'n':
			z.emit('\n')
		case 'r':
			z.emit('\r')
		case 't':
			z.emit('\t')
		case 'u':
			z.Esc, z.Hex, z.Digit = escHex, 0, 0
		default:
			z.Bad = true
		}
		return
	}
	switch {
	case c == '\\':
		z.flushUTF8()
		z.Esc = escBackslash
	case c == '"':
		z.flushUTF8()
		if z.High != 0 {
			z.emit(unicode.ReplacementChar)
			z.High = 0
		}
		z.endString()
	case c < 0x20:
		z.Bad = true
	default:
		if z.High != 0 {
			z.emit(unicode.ReplacementChar)
			z.High = 0
		}
		if len(z.UTF8) == 0 && c < utf8.RuneSelf {
			z.emit(rune(c))
			return
		}
		z.UTF8 = append(z.UTF8, c)
		for len(z.UTF8) > 0 && utf8.FullRune(z.UTF8) {
			r, size := utf8.DecodeRune(z.UTF8)
			z.emit(r)
			z.UTF8 = append(z.UTF8[:0], z.UTF8[size:]...)
		}
	}
}

func hexValue(c byte) int {
	switch {
	case c >= '0' && c <= '9':
		return int(c - '0')
	case c >= 'a' && c <= 'f':
		return int(c-'a') + 10
	case c >= 'A' && c <= 'F':
		return int(c-'A') + 10
	}
	return -1
}

// unit takes one \uXXXX code unit, pairing surrogates as encoding/json does:
// a high surrogate waits for a low one, and either alone becomes U+FFFD.
func (z *rowScan) unit(u rune) {
	if z.High != 0 {
		high := rune(z.High)
		z.High = 0
		if r := utf16.DecodeRune(high, u); r != unicode.ReplacementChar {
			z.emit(r)
			return
		}
		z.emit(unicode.ReplacementChar)
	}
	switch {
	case u >= 0xD800 && u < 0xDC00:
		z.High = int(u)
	case utf16.IsSurrogate(u):
		z.emit(unicode.ReplacementChar)
	default:
		z.emit(u)
	}
}

// flushUTF8 turns an incomplete UTF-8 sequence into U+FFFD, one per byte.
func (z *rowScan) flushUTF8() {
	for len(z.UTF8) > 0 {
		r, size := utf8.DecodeRune(z.UTF8)
		z.emit(r)
		z.UTF8 = append(z.UTF8[:0], z.UTF8[size:]...)
	}
}

func (z *rowScan) emit(r rune) {
	if z.Which >= 0 && z.Which < len(z.Texts) {
		z.Texts[z.Which].rune(r)
	}
}

func (z *rowScan) endString() {
	switch z.Feed {
	case feedKey:
		if len(z.Stack) == 0 {
			z.Bad = true // only a damaged saved state gets here
			return
		}
		frame := &z.Stack[len(z.Stack)-1]
		frame.Key, frame.Long = decodeRaw(z.Buf, z.Long, scanMaxKey)
		z.State = scanColon
		return
	case feedField:
		if z.Which >= 0 && z.Which < fieldCount {
			if z.Long {
				z.Fields[z.Which] = []byte("\x00")
			} else {
				z.Fields[z.Which] = append([]byte(nil), z.Buf...)
			}
		}
	}
	z.State = scanAfter
}

// decodeRaw decodes a raw key with escapes, as a map key is decoded.
func decodeRaw(raw []byte, long bool, limit int) ([]byte, bool) {
	if long {
		return nil, true
	}
	if bytes.IndexByte(raw, '\\') < 0 {
		return append([]byte(nil), raw...), false
	}
	var s string
	if json.Unmarshal(append(append([]byte{'"'}, raw...), '"'), &s) != nil || len(s) > limit {
		return nil, true
	}
	return []byte(s), false
}

func (z *rowScan) endLiteral() {
	switch z.LitRole {
	case roleFlag:
		if z.Which >= 0 && z.Which < flagCount {
			z.Flags[z.Which] = string(z.Lit) == "true"
		}
	case roleItem:
		if string(z.Lit) != "null" {
			z.BadItem = true // decoding the items into objects would fail
		}
	}
	z.LitRole = roleSkip
	z.State = scanAfter
}

func (z *rowScan) pop() {
	if z.inItem() {
		item := &z.Texts[textItem]
		item.finish()
		switch z.field(fieldItemType) {
		case "text":
			z.Texts[textRow].merge(item)
		case "tool_result":
			z.ToolResult = true
		}
		*item = ctlText{}
	}
	z.Stack = z.Stack[:len(z.Stack)-1]
	if len(z.Stack) == 0 {
		z.State = scanEnd
	} else {
		z.State = scanAfter
	}
}

// field decodes a kept field; a missing, long or invalid one is "" or "\x00".
func (z *rowScan) field(i int) string {
	raw := z.Fields[i]
	if len(raw) == 1 && raw[0] == 0 {
		return "\x00"
	}
	var s string
	if raw == nil || json.Unmarshal(append(append([]byte{'"'}, raw...), '"'), &s) != nil {
		return ""
	}
	return s
}

// verdict returns the record control the finished row gives and its
// timestamp. It applies the parser's rules for a row it decodes whole.
func (z *rowScan) verdict(s Source) (control, ts string) {
	if z.Partial || z.Bad || z.State != scanEnd {
		return "", ""
	}
	ts = z.field(fieldTimestamp)
	if _, err := time.Parse(time.RFC3339Nano, ts); err != nil {
		return "", ""
	}
	switch s.Host {
	case "claude-code":
		if z.field(fieldSession) != s.Session || !sameCwd(z.field(fieldCwd), s.Cwd) || z.Flags[flagMeta] || z.Flags[flagSidechain] {
			return "", ts
		}
		if z.field(fieldAgent) != "" || z.field(fieldAgentAlt) != "" {
			return "", ts
		}
		if origin := z.field(fieldTurnOrigin); origin != "" && origin != "human" {
			return "", ts
		}
		if kind := z.field(fieldOriginKind); z.OriginObj && kind != "" && kind != "human" {
			return "", ts
		}
		if !z.MessageObj || z.field(fieldType) != "user" || z.field(fieldRole) != "user" || z.Flags[flagCompact] || z.Flags[flagRepeats] {
			return "", ts
		}
		if z.Content != 1 && (z.Content != 2 || z.ToolResult || z.BadItem) {
			return "", ts
		}
		return z.Texts[textRow].control(), ts
	case "codex":
		if z.field(fieldType) != "event_msg" || !z.PayloadObj || z.field(fieldPayloadType) != "user_message" {
			return "", ts
		}
		return z.Texts[textPayload].control(), ts
	}
	return "", ts
}

// ctlText follows session.RecordControl over a text fed one rune at a time.
// It keeps only what the check needs, so a text of any length takes a few
// hundred bytes of state. Words are runs of runes that are neither white
// space, punctuation nor symbols, lower-cased; the text is a control when its
// first words are a phrase, or when one of its lines is exactly a phrase.
type ctlText struct {
	Any    bool     `json:"any,omitempty"`   // a rune other than white space
	Lead   []byte   `json:"lead,omitempty"`  // the start of the text after leading white space
	Head   []string `json:"head,omitempty"`  // the text's first words, at most four
	Line   []string `json:"line,omitempty"`  // the current line's words, at most four
	Many   bool     `json:"many,omitempty"`  // the current line has more words
	Word   []byte   `json:"word,omitempty"`  // the current word, lower-cased
	InWord bool     `json:"in,omitempty"`    // a word is open
	Long   bool     `json:"wlong,omitempty"` // the current word is too long to match
	Off    bool     `json:"off,omitempty"`   // a line is exactly "off the record"
	On     bool     `json:"on,omitempty"`    // a line is exactly "back on the record"
	Done   bool     `json:"done,omitempty"`
}

const (
	ctlLead = 64 // longer than every synthetic prefix
	ctlWord = 16 // longer than every phrase word
)

func (c *ctlText) rune(r rune) {
	space := unicode.IsSpace(r)
	if !space {
		c.Any = true
	}
	if c.Any && len(c.Lead) < ctlLead {
		c.Lead = utf8.AppendRune(c.Lead, r)
	}
	switch {
	case r == '\n':
		c.endWord()
		c.endLine()
	case space || unicode.IsPunct(r) || unicode.IsSymbol(r):
		c.endWord()
	default:
		c.InWord = true
		lower := unicode.ToLower(r)
		if len(c.Word)+utf8.RuneLen(lower) > ctlWord {
			c.Long = true
		} else {
			c.Word = utf8.AppendRune(c.Word, lower)
		}
	}
}

func (c *ctlText) endWord() {
	if !c.InWord {
		return
	}
	word := string(c.Word)
	if c.Long {
		word = "\x00" // matches no phrase word
	}
	if len(c.Head) < 4 {
		c.Head = append(c.Head, word)
	}
	if len(c.Line) < 4 {
		c.Line = append(c.Line, word)
	} else {
		c.Many = true
	}
	c.Word, c.InWord, c.Long = c.Word[:0], false, false
}

func (c *ctlText) endLine() {
	if !c.Many {
		switch strings.Join(c.Line, " ") {
		case "off the record":
			c.Off = true
		case "back on the record":
			c.On = true
		}
	}
	c.Line, c.Many = c.Line[:0], false
}

func (c *ctlText) finish() {
	if c.Done {
		return
	}
	c.endWord()
	c.endLine()
	c.Done = true
}

// merge appends a finished item's text as if joined with "\n", as userText
// joins the text items. Only the first item with any content supplies the
// lead, since no synthetic prefix holds a newline.
func (c *ctlText) merge(item *ctlText) {
	c.Off = c.Off || item.Off
	c.On = c.On || item.On
	for _, w := range item.Head {
		if len(c.Head) < 4 {
			c.Head = append(c.Head, w)
		}
	}
	if !c.Any && item.Any {
		c.Any = true
		c.Lead = append([]byte(nil), item.Lead...)
	}
}

// control returns what the parser's check gives for the text: nothing for
// empty or synthetic text, otherwise session.RecordControl's answer.
func (c *ctlText) control() string {
	c.finish()
	if !c.Any || syntheticText(string(c.Lead)) {
		return ""
	}
	return c.verdict()
}

// verdict returns session.RecordControl's answer for the text fed so far.
func (c *ctlText) verdict() string {
	c.finish()
	starts := func(words ...string) bool {
		if len(c.Head) < len(words) {
			return false
		}
		for i, w := range words {
			if c.Head[i] != w {
				return false
			}
		}
		return true
	}
	switch {
	case c.Off || starts("off", "the", "record"):
		return "off_record"
	case c.On || starts("back", "on", "the", "record"):
		return "on_record"
	}
	return ""
}

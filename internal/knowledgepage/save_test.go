// TestSaveWritesPagesMapAndIndexes checks a first save: the pages as okf
// saves them, the map, the folder's index, the recall index, the root
// index's line, okf's validator, and the pages read back through okf and
// without it.
func TestSaveWritesPagesMapAndIndexes(t *testing.T) {
	w := fixture(t)
	r := save(t, w, meta(), addInbox, addOffline)
	if !slices.Equal(r.Created, []int{1, 2}) || r.Pages != 2 || len(r.Skipped) != 0 || r.PathsDropped != 0 {
		t.Fatalf("result = %+v", r)
	}
	wantFiles := []string{"knowledge/k1.md", "knowledge/k2.md", "knowledge/map.md", "knowledge/index.md", ".eva-md/knowledge.tsv", "index.md"}
	if !slices.Equal(r.Files, wantFiles) {
		t.Errorf("files = %q, want %q", r.Files, wantFiles)
	}
	if got := withoutGenerated(readFile(t, w, "knowledge/k1.md")); got != pageK1 {
		t.Errorf("k1.md =\n%s\nwant\n%s", got, pageK1)
	}
	if got := withoutGenerated(readFile(t, w, "knowledge/k2.md")); got != pageK2 {
		t.Errorf("k2.md =\n%s\nwant\n%s", got, pageK2)
	}
	if !strings.Contains(readFile(t, w, "knowledge/k1.md"), "generated: { by: "+actor+", at: ") {
		t.Error("k1.md is not generated by the update's actor")
	}
	wantMap := `---
type: map
title: Knowledge map
description: "Every knowledge page, one line each"
status: stable
---

# Knowledge map

- [Inbox format](k1.md): decision · this project · github.com__acme__eva · as of 2026-10-28
- [Hooks stay offline](k2.md): constraint · all projects · github.com__acme__eva · as of 2026-10-28
`
	if got := withoutGenerated(readFile(t, w, "knowledge/map.md")); got != wantMap {
		t.Errorf("map.md =\n%s\nwant\n%s", got, wantMap)
	}
	if !strings.Contains(readFile(t, w, "knowledge/map.md"), "generated: { by: eva-md/test, at: ") {
		t.Error("the map is not eva-md's own page")
	}
	wantIndex := "# Knowledge\n\n" +
		"* [Inbox format](k1.md) - The inbox stores entries as JSONL, one file per session\n" +
		"* [Hooks stay offline](k2.md) - Hooks never make a network call\n" +
		"* [Knowledge map](map.md) - Every knowledge page, one line each\n"
	if got := readFile(t, w, "knowledge/index.md"); got != wantIndex {
		t.Errorf("index.md =\n%s\nwant\n%s", got, wantIndex)
	}
	wantTSV := "# eva-md knowledge index 1\n" +
		"k2\tconstraint\tstated\tall\tgithub.com__acme__eva\t2026-10-28\t2026-10-28T10:00:00+01:00\t\tHooks stay offline\tHooks never make a network call\t\n" +
		"k1\tdecision\tstated\tproject\tgithub.com__acme__eva\t2026-10-28\t2026-10-28T10:00:00+01:00\t\tInbox format\tThe inbox stores entries as JSONL, one file per session\tinternal/inbox\n"
	if got := readFile(t, w, IndexFile); got != wantTSV {
		t.Errorf("knowledge.tsv =\n%q\nwant\n%q", got, wantTSV)
	}
	if info, err := os.Stat(filepath.Join(w.Root(), IndexFile)); err != nil || info.Mode().Perm() != 0o600 {
		t.Errorf("knowledge.tsv mode: %v, %v", info, err)
	}
	if root := readFile(t, w, "index.md"); !strings.HasSuffix(root, rootLine) || strings.Count(root, "](knowledge/index.md)") != 1 {
		t.Errorf("root index =\n%s", root)
	}
	if log := readFile(t, w, "log.md"); !strings.Contains(log, "Documented concept `knowledge/k1.md`") {
		t.Errorf("log.md has no line for k1:\n%s", log)
	}
	validate(t, w)

	want := Entry{ID: 1, Kind: Decision, Title: "Inbox format", Statement: "The inbox stores entries as JSONL, one file per session", Tag: "stated",
		Scope: ScopeProject, Project: project, State: Active, AsOf: "2026-10-28", At: at1, Refs: []string{"s:3f2a91c0#14"},
		Sources: []string{"s:3f2a91c0#14"}, Code: []string{"github.com__acme__eva@4e2bf4c:internal/inbox"}, Paths: []string{"internal/inbox"}}
	got := entry(t, w, 1)
	if !reflect.DeepEqual(got, want) {
		t.Errorf("Read k1 =\n%+v\nwant\n%+v", got, want)
	}
	lenient, ok := Lenient([]byte(readFile(t, w, "knowledge/k1.md")))
	lenient.ID = 1
	if !ok || !reflect.DeepEqual(lenient, want) {
		t.Errorf("Lenient k1 = %v\n%+v\nwant\n%+v", ok, lenient, want)
	}
	for _, s := range got.Code {
		if r, ok := coderef.Parse(s); !ok || r.Key != project || r.Commit != commit {
			t.Errorf("coderef.Parse(%q) = %+v, %v", s, r, ok)
		}
	}
	if got.Render() != withoutGenerated(readFile(t, w, "knowledge/k1.md")) {
		t.Errorf("Render =\n%s\nwant the saved page", got.Render())
	}
}

// TestSaveIsIdempotent checks that running the same operations again, as an
// update does after a failed thread save, writes nothing.
func TestSaveIsIdempotent(t *testing.T) {
	w := fixture(t)
	save(t, w, meta(), addInbox, addOffline)
	before := snapshot(t, w)
	r := save(t, w, meta(), addInbox, addOffline)
	if len(r.Created)+r.Pages+len(r.Files) != 0 || !reflect.DeepEqual(r.Skipped, []Skip{{0, 0, ReasonDuplicate}, {1, 0, ReasonDuplicate}}) {
		t.Errorf("rerun of the adds = %+v", r)
	}
	if after := snapshot(t, w); !reflect.DeepEqual(after, before) {
		t.Error("a rerun of the adds changed the wiki")
	}
	save(t, w, meta(), supersedeInbox, dropOffline)
	before = snapshot(t, w)
	r = save(t, w, meta(), supersedeInbox, dropOffline)
	if len(r.Superseded)+len(r.Dropped)+r.Pages+len(r.Files) != 0 || !reflect.DeepEqual(r.Skipped, []Skip{{0, 1, ReasonSame}, {1, 2, ReasonRetired}}) {
		t.Errorf("rerun of the supersede and the drop = %+v", r)
	}
	if after := snapshot(t, w); !reflect.DeepEqual(after, before) {
		t.Error("a rerun of the supersede and the drop changed the wiki")
	}
	// An add that only differs in case and punctuation is the same
	// statement.
	r = save(t, w, meta(), Op{Action: Add, Kind: Fact, Title: "Again", Text: "the INBOX stores entries as jsonl; one file per session, and day.", Tag: "stated", At: at2})
	if len(r.Created) != 0 || len(r.Skipped) != 1 || r.Skipped[0].Reason != ReasonDuplicate {
		t.Errorf("a restated add = %+v", r)
	}
}

// TestSupersedeAndDropKeepHistory checks the History lines a supersede and
// a drop add, the statement, date and sources they move, and the map and
// recall index after them.
func TestSupersedeAndDropKeepHistory(t *testing.T) {
	w := fixture(t)
	save(t, w, meta(), addInbox, addOffline)
	r := save(t, w, meta(), supersedeInbox, dropOffline)
	if !slices.Equal(r.Superseded, []int{1}) || !slices.Equal(r.Dropped, []int{2}) || r.Pages != 2 {
		t.Fatalf("result = %+v", r)
	}
	k1 := entry(t, w, 1)
	wantHistory := []string{"- ~~The inbox stores entries as JSONL, one file per session~~ → The inbox stores entries as JSONL, one file per session and day (superseded 2026-10-31) [stated] s:4b5c6d7e#3"}
	if !slices.Equal(k1.History, wantHistory) || k1.Statement != supersedeInbox.Text || k1.AsOf != "2026-10-31" || !k1.At.Equal(at2) ||
		!slices.Equal(k1.Refs, []string{"s:4b5c6d7e#3"}) || !slices.Equal(k1.Sources, []string{"s:3f2a91c0#14", "s:4b5c6d7e#3"}) || len(k1.Code) != 1 || k1.State != Active {
		t.Errorf("k1 after the supersede = %+v", k1)
	}
	body := readFile(t, w, "knowledge/k1.md")
	if !strings.Contains(body, "\n## Statement\nThe inbox stores entries as JSONL, one file per session and day [stated] s:4b5c6d7e#3 <!-- t:2026-10-31T00:30:00+01:00 -->\n\n## History\n"+wantHistory[0]+"\n\nPart of the [knowledge map](map.md).\n") {
		t.Errorf("k1.md =\n%s", body)
	}
	k2 := entry(t, w, 2)
	wantHistory = []string{"- ~~Hooks never make a network call~~ (retired 2026-10-31: the user allowed the update job to call the model) [stated] s:4b5c6d7e#4"}
	if !slices.Equal(k2.History, wantHistory) || k2.State != Retired || k2.Statement != addOffline.Text || k2.AsOf != "2026-10-28" {
		t.Errorf("k2 after the drop = %+v", k2)
	}
	m := readFile(t, w, "knowledge/map.md")
	for _, l := range []string{
		"- [Inbox format](k1.md): decision · this project · github.com__acme__eva · as of 2026-10-31\n",
		"- [Hooks stay offline](k2.md): constraint · all projects · github.com__acme__eva · as of 2026-10-28 · retired\n",
	} {
		if !strings.Contains(m, l) {
			t.Errorf("the map has no line %q:\n%s", l, m)
		}
	}
	rows := ParseIndex([]byte(readFile(t, w, IndexFile)))
	if len(rows) != 1 || rows[0].ID != "k1" || rows[0].Statement != supersedeInbox.Text {
		t.Errorf("recall index rows = %+v", rows)
	}
	validate(t, w)

	// A drop without a reason, and a supersede that changes the kind, title
	// and scope and cites new code.
	r = save(t, w, meta(), Op{Action: Supersede, ID: 1, Kind: Fact, Title: "Inbox files", Text: "Each session has one JSONL file in the inbox", Tag: "observed", Scope: ScopeAll,
		Refs: []string{"s:4b5c6d7e#9"}, At: at2.Add(time.Hour), Paths: []string{"internal/inbox/store.go"}})
	k1 = entry(t, w, 1)
	if !slices.Equal(r.Superseded, []int{1}) || k1.Kind != Fact || k1.Title != "Inbox files" || k1.Scope != ScopeAll || k1.Tag != "observed" ||
		!slices.Equal(k1.Paths, []string{"internal/inbox/store.go"}) || len(k1.History) != 2 {
		t.Errorf("k1 after a second supersede = %+v", k1)
	}
	save(t, w, meta(), addInbox)
	r = save(t, w, meta(), Op{Action: Drop, ID: 3, Tag: "accepted", At: at2})
	if k3 := entry(t, w, 3); !slices.Equal(r.Dropped, []int{3}) || !slices.Equal(k3.History, []string{"- ~~" + addInbox.Text + "~~ (retired 2026-10-31) [accepted]"}) {
		t.Errorf("a drop without a reason = %+v, %+v", r, k3.History)
	}
	validate(t, w)
}

// TestIDsAreNeverReused checks that a new page takes one more than the
